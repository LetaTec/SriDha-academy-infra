// Writes api/src/db/topicLibrary.ts from the website's topic list, so the
// API seed (prices, lessons) and the topic cards never drift apart.
// Run with: npm run topics:export
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { TOPIC_PREVIEWS } from '../web/src/constants/topics';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'api/src/db/topicLibrary.ts');

const entries = TOPIC_PREVIEWS.map(topic => ({
  id: topic.catalogueTopicId,
  subject: topic.subject,
  level: topic.level,
  title: topic.title,
  lessons: [...topic.subtopics],
}));

writeFileSync(
  target,
  `// Generated by scripts/export-topic-library.ts from
// web/src/constants/topics.ts. Do not edit by hand: change the website's
// topic list and run \`npm run topics:export\`.

export type LibrarySubject =
  | 'accountancy'
  | 'businessStudies'
  | 'economics'
  | 'physics'
  | 'chemistry'
  | 'mathematics'
  | 'biology';

export type LibraryTopic = {
  id: string;
  subject: LibrarySubject;
  level: string;
  title: string;
  lessons: readonly string[];
};

export const TOPIC_LIBRARY: readonly LibraryTopic[] = ${JSON.stringify(entries, null, 2)};
`,
);

console.log(
  `[topics] wrote ${entries.length} topics to ${path.relative(root, target)}`,
);
